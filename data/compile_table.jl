# compile_table.jl — compile.tex for the Model Compilation Time subsection.
# Block 1 (per framework, only if ready_*.csv artifacts exist): time from data
# in hand to solver-ready NLP functions, compilation parenthesized where
# separable. Block 2 (ExaModels): Julia compilation time against problem size
# and kernel count, on CPU and GPU.
# The retired compare_cold_* filename family must not be read here.
using CSV, DataFrames, Printf, Statistics

const RESULTS = joinpath(@__DIR__, "results")
const SOLVE_RESULTS = normpath(joinpath(@__DIR__, "..", "solve", "results"))
const OUT_DIR = joinpath(@__DIR__, "build", "tables")

const READY_ORDER = ["examodels" => "ExaModels", "jax" => "JAX",
                     "torch" => "PyTorch", "casadi" => "CasADi"]

fmt_s(x) = x >= 10 ? @sprintf("%.1f", x) : x >= 1 ? @sprintf("%.2f", x) : @sprintf("%.3f", x)
fmt_ms(x) = x >= 1000 ? @sprintf("%.1f\\,s", x / 1000) : @sprintf("%.0f", x)

read_all(dir, pat) = begin
    isdir(dir) || return DataFrame()
    fs = filter(f -> occursin(pat, basename(f)), joinpath.(dir, readdir(dir)))
    isempty(fs) && return DataFrame()
    reduce((a, b) -> vcat(a, b, cols = :union), [CSV.read(f, DataFrame) for f in fs])
end

# --------------------------------------------------------------- ready table
fmt_int(n) = replace(string(n), r"(?<=[0-9])(?=(?:[0-9]{3})+$)" => "{,}")
fmt_rs(x) = x >= 100 ? @sprintf("%.0f", x) : x >= 10 ? @sprintf("%.1f", x) : @sprintf("%.2f", x)
casehead(c) = (m = match(r"case(\d+)", String(c)); m === nothing ? String(c) : "case" * m[1])

# platform label for the caption, from the scaling CSV filenames + label map
function scaling_platform()
    hs = String[]
    for dir in (SOLVE_RESULTS, RESULTS)
        isdir(dir) || continue
        for f in readdir(dir)
            m = match(r"^compile_scaling_(.+?)_(?:cpu|cuda)\.csv$", f)
            m === nothing || push!(hs, m[1])
        end
        isempty(hs) || break
    end
    length(unique(hs)) == 1 || return nothing
    lf = joinpath(@__DIR__, "build", "_labels.toml")
    isfile(lf) || return nothing
    m = match(Regex("^\"" * first(unique(hs)) * "\"\\s*=\\s*\"([A-Z]+[0-9]+)\"", "m"), read(lf, String))
    m === nothing && return nothing
    lab = String(m[1])
    words = Dict(1 => "One", 2 => "Two", 3 => "Three", 4 => "Four", 5 => "Five",
                 6 => "Six", 7 => "Seven", 8 => "Eight", 9 => "Nine", 10 => "Ten")
    w = match(r"^([A-Z]+)([0-9]+)$", lab)
    w === nothing && return nothing
    (lab, w[1] * get(words, parse(Int, w[2]), ""))
end

function write_compile(path)
    ready = read_all(RESULTS, r"^ready_.*\.csv$")
    df = read_all(SOLVE_RESULTS, r"^compile_scaling_.*\.csv$")
    nrow(df) == 0 && (df = read_all(RESULTS, r"^compile_scaling_.*\.csv$"))
    if nrow(ready) == 0 && nrow(df) == 0
        @warn "no ready_ or compile_scaling rows; compile.tex not written"
        return
    end
    backends = nrow(df) > 0 ? sort(unique(String.(df.backend))) : String[]
    blabel(b) = b == "cuda" ? "GPU" : "CPU"
    haveready = nrow(ready) > 0

    # Physical width: 2 label columns + max(5 solver-ready numerics,
    # 2 numerics per scaling backend). Short rows pad with empty cells.
    P = 2 + max(5, 2 * max(length(backends), 1))
    pad(k) = repeat(" &", P - k)

    mkpath(dirname(path))
    open(path, "w") do io
        println(io, "% Auto-generated by compile_table.jl — do not edit by hand")
        println(io, raw"\begin{table}[t]")
        plat = scaling_platform()
        attrib = plat === nothing ? "" :
            " Both sweeps ran on platform $(plat[1])."
        if haveready
            println(io, "\\caption{Model creation and compilation time. The upper blocks report the time from data in hand to solver-ready NLP functions, per framework, in seconds; parenthesized, the compilation component where it is separable from construction. The lower block reports Julia compilation time for ExaModels.jl, varying the problem size and the number of distinct constraint kernels; times in milliseconds unless a unit is shown, `model' is compilation during model construction, and `total' additionally includes the first derivative evaluation and the solve.$attrib}")
        else
            println(io, "\\caption{Julia compilation time for ExaModels.jl, varying the problem size and the number of distinct constraint kernels.$attrib}")
        end
        println(io, raw"\label{tab:compile}")
        println(io, raw"\scriptsize")
        println(io, "\\begin{tabular*}{\\textwidth}{@{\\extracolsep{\\fill}}ll", repeat("r", P - 2), "}")
        println(io, raw"  \toprule")

        if haveready
            known = [k for (k, _) in READY_ORDER]
            fworder = sort(unique(String.(ready.framework)),
                           by = f -> (something(findfirst(==(f), known), length(known) + 1), f))
            for (prob, title) in (("lv", "Luk\\v{s}an--Vl\\v{c}ek Rosenbrock, \$N\$"),
                                  ("opf", "AC-OPF"))
                sub = filter(r -> String(r.problem) == prob, ready)
                nrow(sub) == 0 && continue
                cols = sort(unique(sub.n))
                length(cols) > P - 2 && (cols = cols[1:P-2])
                colhead(n) = prob == "lv" ? fmt_int(n) :
                             casehead(first(filter(r -> r.n == n, sub).case))
                println(io, "  \\multicolumn{$P}{@{}l}{\\emph{solver-ready time (s): $title}} \\\\")
                print(io, "  \\textbf{framework} & \\textbf{device}")
                for n in cols
                    print(io, " & ", colhead(n))
                end
                println(io, pad(2 + length(cols)), " \\\\")
                println(io, raw"  \midrule")
                # Fastest solver-ready time per column, for bolding.
                best = Dict(n => minimum(filter(r -> r.n == n, sub).tready_s) for n in cols)
                for f in fworder, dev in ("cpu", "cuda")
                    rows = filter(r -> String(r.framework) == f && String(r.device) == dev, sub)
                    nrow(rows) == 0 && continue
                    lbl = something(get(Dict(READY_ORDER), f, nothing), f)
                    print(io, "  ", lbl, " & ", blabel(dev))
                    for n in cols
                        rn = filter(r -> r.n == n, rows)
                        if nrow(rn) == 0
                            print(io, " & --")
                            continue
                        end
                        r = rn[argmin(rn.tready_s), :]
                        cell = fmt_rs(r.tready_s)
                        if r.separable === true && r.tcompile_s isa Number && r.tcompile_s > 0
                            cell *= " (" * fmt_rs(r.tcompile_s) * ")"
                        end
                        r.tready_s <= best[n] * 1.001 && (cell = "\\textbf{" * cell * "}")
                        print(io, " & ", cell)
                    end
                    println(io, pad(2 + length(cols)), " \\\\")
                end
                println(io, raw"  \midrule")
            end
        end

        if !isempty(backends)
            print(io, " & ")
            for b in backends
                print(io, " & \\multicolumn{2}{c}{\\textbf{$(blabel(b))}}")
            end
            println(io, pad(2 + 2 * length(backends)), " \\\\")
            print(io, "  \\textbf{varying} & \\textbf{value}")
            for _ in backends
                print(io, " & model & total")
            end
            println(io, pad(2 + 2 * length(backends)), " \\\\")
            println(io, raw"  \midrule")
            for (exp, keycol, title) in (("size", :nvar, "problem size \$n\$"),
                                         ("kinds", :nkind, "constraint kernels"))
                sub = filter(r -> String(r.experiment) == exp, df)
                nrow(sub) == 0 && continue
                println(io, "  \\multicolumn{$P}{@{}l}{\\emph{Julia compilation, ExaModels.jl: $title}} \\\\")
                for v in sort(unique(sub[!, keycol]))
                    print(io, "   & ", v)
                    for b in backends
                        r = filter(x -> String(x.backend) == b && x[keycol] == v, sub)
                        if nrow(r) == 0
                            print(io, " & -- & --")
                        else
                            print(io, " & ", fmt_ms(minimum(r.cconstruct_ms)),
                                      " & ", fmt_ms(minimum(r.compile_total_ms)))
                        end
                    end
                    println(io, pad(2 + 2 * length(backends)), " \\\\")
                end
            end
        end

        println(io, raw"  \bottomrule")
        println(io, raw"\end{tabular*}")
        println(io, raw"\end{table}")
    end
    @info "compile table written" file = path ready_rows = nrow(ready) scaling_backends = backends

    # facts the section prose quotes
    open(joinpath(dirname(path), "compile_facts.tex"), "w") do io
        println(io, "% Auto-generated by compile_table.jl — do not edit by hand")
        for (b, w) in (("cpu", "Cpu"), ("cuda", "Gpu"))
            sz = filter(r -> String(r.experiment) == "size" && String(r.backend) == b, df)
            kd = filter(r -> String(r.experiment) == "kinds" && String(r.backend) == b, df)
            if nrow(sz) > 0
                m = [minimum(filter(r -> r.nvar == v, sz).cconstruct_ms) for v in sort(unique(sz.nvar))]
                spread = (maximum(m) - minimum(m)) / minimum(m) * 100
                println(io, "% $w spread of model-construction compilation across the size sweep, percent")
                println(io, "\\newcommand{\\cmpSizeSpread$w}{$(@sprintf("%.1f", spread))}")
            end
            if nrow(kd) > 0
                ks = sort(unique(kd.nkind))
                lo = minimum(filter(r -> r.nkind == first(ks), kd).cconstruct_ms)
                hi = minimum(filter(r -> r.nkind == last(ks), kd).cconstruct_ms)
                println(io, "% $w model-construction compilation ratio, $(first(ks)) kernel(s) to $(last(ks))")
                println(io, "\\newcommand{\\cmpKindsRatio$w}{$(hi / lo >= 3 ? @sprintf("%.1f", hi / lo) : @sprintf("%.2f", hi / lo))}")
                println(io, "% $w kernel-count endpoints of the sweep")
                println(io, "\\newcommand{\\cmpKindsLo$w}{$(first(ks))}")
                println(io, "\\newcommand{\\cmpKindsHi$w}{$(last(ks))}")
                if b == "cuda"
                    println(io, "% GPU model-construction compilation at one kernel, seconds")
                    println(io, "\\newcommand{\\cmpGpuFixedS}{$(@sprintf("%.0f", lo / 1000))}")
                end
            end
        end
    end
end

write_compile(joinpath(OUT_DIR, "compile.tex"))
