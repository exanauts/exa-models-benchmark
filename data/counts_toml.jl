# Write build/_counts.toml: per-callback call counts of one interior-point
# solve, the shared composite-metric weights read by gpu_table.jl and
# compare_table.jl.
# OPF-derived and reused across suites: on LV and COPS the composite is a
# weighting, not a measurement of those solves.
using CSV, DataFrames

const SOLVE_RESULTS = normpath(joinpath(@__DIR__, "..", "solve", "results"))
const OUT = joinpath(@__DIR__, "build", "_counts.toml")

# The featured pipeline of the solve breakdown, and the largest OPF instance.
const WANT_CONFIG = get(ENV, "COUNTS_CONFIG", "gpu-gpu")
const WANT_CASE = get(ENV, "COUNTS_CASE", "78484")
const COLS = ["obj" => :neval_obj, "cons" => :neval_cons, "grad" => :neval_grad,
              "jac" => :neval_jac, "hess" => :neval_hess]

function main()
    isdir(SOLVE_RESULTS) || (@warn "no solve results; _counts.toml not written"; return)
    fs = filter(f -> occursin(r"^breakdown_.*\.csv$", basename(f)),
                joinpath.(SOLVE_RESULTS, readdir(SOLVE_RESULTS)))
    isempty(fs) && (@warn "no breakdown CSVs; _counts.toml not written"; return)
    df = reduce((a, b) -> vcat(a, b, cols = :union),
                [CSV.read(f, DataFrame) for f in fs])
    # older bundles carry no neval_* columns; skip rather than write zeros
    hasproperty(df, :neval_obj) ||
        (@warn "breakdown rows carry no neval_* columns; rerun the solve leg. _counts.toml not written"; return)
    df = dropmissing(df, :neval_obj)
    sub = filter(r -> occursin(WANT_CASE, String(r.case)), df)
    nrow(sub) == 0 && (@warn "no rows for case $WANT_CASE; _counts.toml not written"; return)
    pick = filter(r -> String(r.config) == WANT_CONFIG, sub)
    nrow(pick) == 0 && (@warn "no $WANT_CONFIG rows; _counts.toml not written"; return)
    # Newest run wins, matching the recency rule used everywhere else.
    sort!(pick, :timestamp, rev = true)
    r = pick[1, :]

    mkpath(dirname(OUT))
    open(OUT, "w") do io
        println(io, "# Auto-generated by counts_toml.jl — do not edit by hand.")
        println(io, "#")
        println(io, "# Callback counts for ONE interior-point solve, used as shared weights for")
        println(io, "# the composite evaluation-time metric. A property of the solver's")
        println(io, "# trajectory, not of the framework evaluating the callbacks.")
        println(io, "#")
        println(io, "# OPF-DERIVED AND REUSED ACROSS SUITES: on LV and COPS the composite is a")
        println(io, "# weighting, not a measurement of those solves.")
        println(io, "#")
        println(io, "# Alternatives measured in the same run, for reference:")
        for g in eachrow(sort(sub, :config))
            println(io, "#   ", rpad(String(g.config), 9), " iter=", g.iter,
                    "  obj=", g.neval_obj, " cons=", g.neval_cons,
                    " grad=", g.neval_grad, " jac=", g.neval_jac, " hess=", g.neval_hess)
        end
        println(io)
        println(io, "source_config = \"", r.config, "\"")
        println(io, "source_case = \"", r.case, "\"")
        println(io, "source_host = \"", r.hostname, "\"")
        println(io, "source_device = \"", r.device, "\"")
        println(io, "source_timestamp = \"", r.timestamp, "\"")
        println(io, "iterations = ", r.iter)
        println(io)
        # top-level keys, not a [counts] table: the readers expect d["obj"]
        for (k, c) in COLS
            println(io, k, " = ", r[c])
        end
    end
    @info "counts written" file = OUT config = r.config case = r.case iter = r.iter
end

main()
